// =========================================================
// utils.js — generic helpers used across the app.
// Security note: `h()` builds DOM nodes directly (textContent,
// setAttribute) instead of innerHTML, so user-entered data can
// never be interpreted as markup. Avoid innerHTML with dynamic
// data anywhere else in the app — use h()/escapeHtml() instead.
// =========================================================

/** Build a DOM element safely. props may include: class, attrs{}, on{event:fn}, html(trusted-only) */
export function h(tag, props = {}, children = []) {
  const el = document.createElement(tag);
  if (props.class) el.className = props.class;
  if (props.id) el.id = props.id;
  if (props.attrs) {
    for (const [k, v] of Object.entries(props.attrs)) {
      if (v !== null && v !== undefined && v !== false) el.setAttribute(k, v === true ? "" : v);
    }
  }
  if (props.on) {
    for (const [ev, fn] of Object.entries(props.on)) el.addEventListener(ev, fn);
  }
  if (props.style) Object.assign(el.style, props.style);
  // `trustedHtml` is only for static, developer-authored markup (e.g. inline SVG icons),
  // never for user-supplied strings.
  if (props.trustedHtml !== undefined) el.innerHTML = props.trustedHtml;

  const kids = Array.isArray(children) ? children : [children];
  for (const kid of kids) {
    if (kid === null || kid === undefined || kid === false) continue;
    if (typeof kid === "string" || typeof kid === "number") {
      el.appendChild(document.createTextNode(String(kid)));
    } else {
      el.appendChild(kid);
    }
  }
  return el;
}

export function clear(el) { while (el.firstChild) el.removeChild(el.firstChild); }

export function mount(container, node) { clear(container); container.appendChild(node); }

export function escapeHtml(str) {
  return String(str ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[c]));
}

export function uuid() {
  if (crypto.randomUUID) return crypto.randomUUID();
  return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (c) => {
    const r = (crypto.getRandomValues(new Uint8Array(1))[0] % 16);
    const v = c === "x" ? r : (r & 0x3 | 0x8);
    return v.toString(16);
  });
}

export function nowIso() { return new Date().toISOString(); }

/** Display date as DD/MM/YYYY regardless of stored ISO 8601 format (section 6). */
export function formatDateDisplay(iso) {
  if (!iso) return "—";
  const d = new Date(iso);
  if (isNaN(d)) return "—";
  const dd = String(d.getDate()).padStart(2, "0");
  const mm = String(d.getMonth() + 1).padStart(2, "0");
  const yyyy = d.getFullYear();
  return `${dd}/${mm}/${yyyy}`;
}

export function toIsoDateOnly(dateInputValue) {
  // dateInputValue from <input type=date> is already YYYY-MM-DD
  if (!dateInputValue) return null;
  return new Date(dateInputValue + "T00:00:00").toISOString();
}

export function formatCurrency(amount) {
  const n = Number(amount) || 0;
  return n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }) + " ج.م";
}

export function debounce(fn, wait = 300) {
  let t;
  return (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), wait); };
}

export function bytesToSize(bytes) {
  if (!bytes) return "0 KB";
  const units = ["B", "KB", "MB", "GB"];
  let i = 0, n = bytes;
  while (n >= 1024 && i < units.length - 1) { n /= 1024; i++; }
  return `${n.toFixed(i === 0 ? 0 : 1)} ${units[i]}`;
}

export function toast(message, type = "info", ms = 2800) {
  const region = document.getElementById("toast-region");
  if (!region) return;
  clear(region); // keep only the latest toast on screen — avoids stacked/overlapping messages
  const t = h("div", { class: `toast ${type}` }, message);
  region.appendChild(t);
  setTimeout(() => {
    t.classList.add("hide");
    setTimeout(() => t.remove(), 220);
  }, ms);
}

export function initials(name) {
  const trimmed = (name || "").trim();
  if (!trimmed) return "؟";
  return trimmed[0];
}

/** Simple phone format check — Egyptian mobile numbers (01xxxxxxxxx) or generic. */
export function isValidPhone(phone) {
  if (!phone) return true; // optional field
  const cleaned = phone.replace(/[\s\-()]/g, "");
  return /^(01[0-2,5]\d{8}|0\d{8,10}|\+?\d{8,14})$/.test(cleaned);
}

